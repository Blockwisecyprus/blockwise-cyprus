  function applyYachtLanguage(lang) {
    lang = lang === "el" ? "el" : "en";
    document.querySelectorAll("[data-v27-i18n]").forEach(function (el) {
      const key = el.getAttribute("data-v27-i18n");
      if (copy[lang] && copy[lang][key]) el.textContent = copy[lang][key];
    });
  }

  function detectLanguage() {
    const htmlLang = (document.documentElement.getAttribute("lang") || "").toLowerCase();
    if (htmlLang.startsWith("el")) return "el";

    const gr = document.querySelector('[data-lang="el"]');
    const en = document.querySelector('[data-lang="en"]');

    if (gr && (gr.classList.contains("active") || gr.getAttribute("aria-pressed") === "true")) return "el";
    if (en && (en.classList.contains("active") || en.getAttribute("aria-pressed") === "true")) return "en";

    for (const key of ["blockwiseLang", "language", "lang", "siteLanguage"]) {
      const value = localStorage.getItem(key);
      if (value === "el" || value === "gr" || value === "greek") return "el";
      if (value === "en" || value === "english") return "en";
    }
    return "en";
  }

  document.querySelectorAll("[data-lang]").forEach(function (button) {
    button.addEventListener("click", function () {
      const chosen = button.getAttribute("data-lang") === "el" ? "el" : "en";
      applyYachtLanguage(chosen);
      setTimeout(function () { applyYachtLanguage(chosen); }, 50);
      setTimeout(function () { applyYachtLanguage(chosen); }, 250);
    }, true);
  });

  applyYachtLanguage(detectLanguage());
  setTimeout(function () { applyYachtLanguage(detectLanguage()); }, 300);
  setTimeout(function () { applyYachtLanguage(detectLanguage()); }, 1000);
